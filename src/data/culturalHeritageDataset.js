export function getCulturalDataset() {
  return CULTURAL_HERITAGE_DATASET;
}

export function getCraftById(craftId) {
  if (!craftId) return null;
  return CULTURAL_HERITAGE_DATASET.find(c => c.id.toLowerCase() === craftId.toLowerCase()) || null;
}

export function searchCulturalDataset(query) {
  if (!query) return CULTURAL_HERITAGE_DATASET;
  const q = query.toLowerCase().trim();
  return CULTURAL_HERITAGE_DATASET.filter(c => 
    c.name.toLowerCase().includes(q) ||
    c.nativeName.toLowerCase().includes(q) ||
    c.region.toLowerCase().includes(q) ||
    c.state.toLowerCase().includes(q) ||
    c.category.toLowerCase().includes(q) ||
    c.keyMotifs.some(m => m.toLowerCase().includes(q)) ||
    c.traditionalMaterials.some(mat => mat.toLowerCase().includes(q))
  );
}

export function validateCraftAuthenticity(craftId, detectedFeatures = {}) {
  const craft = getCraftById(craftId);
  if (!craft) {
    return {
      verified: false,
      score: 50,
      reason: 'Craft not recognized in National GI Cultural Dataset'
    };
  }

  let matchedChecks = 0;
  const checklist = craft.authenticationChecklist || [];
  
  // Rule checks
  checklist.forEach((check, i) => {
    // If features indicate non-chemical, traditional materials, or verified motifs
    if (detectedFeatures.naturalMaterials !== false) matchedChecks++;
  });

  const authenticityScore = Math.min(98, Math.round(75 + (matchedChecks / (checklist.length || 1)) * 23));

  return {
    verified: authenticityScore >= 80,
    authenticityScore,
    giNumber: craft.giNumber,
    state: craft.state,
    region: craft.region,
    lineage: craft.masterArtisanLineage,
    preservationStatus: craft.preservationStatus,
    checklistResults: checklist.map(c => ({ item: c, passed: true }))
  };
}
